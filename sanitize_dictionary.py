def sanitize_meaning(word, meaning):
    # 1. Exact match override
    if word in EXACT_CORRECTIONS:
        return EXACT_CORRECTIONS[word]

    cleaned = meaning

    # 2. Sadhu replacements
    for old_s, new_s in SADHU_REPLACEMENTS:
        cleaned = cleaned.replace(old_s, new_s)

    # 3. Purge toxic fragments
    for tf in TOXIC_SUBSTRINGS:
        cleaned = cleaned.replace(tf, '')

    # 4. Clean up punctuation
    parts = [p.strip() for p in re.split(r'[,،;]+', cleaned) if p.strip()]
    
    # Deduplicate keeping order
    seen = set()
    uniq = []
    for p in parts:
        if p not in seen:
            seen.add(p)
            uniq.append(p)
            
    res = ', '.join(uniq)
    # If emptied by filtering, fallback to clean meaning
    if not res:
        res = meaning
    return res


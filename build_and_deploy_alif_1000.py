# Collation sorting
urdu_alphabet = [
    'آ', 'ا', 'ب', 'پ', 'ت', 'ٹ', 'ث', 'ج', 'چ', 'ح', 'خ',
    'د', 'ڈ', 'ذ', 'ر', 'ڑ', 'ز', 'ژ', 'س', 'ش', 'ص', 'ض',
    'ط', 'ظ', 'ع', 'غ', 'ف', 'ق', 'ک', 'گ', 'ل', 'م', 'ن',
    'ں', 'و', 'ہ', 'ھ', 'ء', 'ی', 'ئ', 'ے'
]
urdu_rank = {ch: i for i, ch in enumerate(urdu_alphabet)}

def urdu_sort_key(word):
    return [urdu_rank.get(ch, 999) for ch in word]


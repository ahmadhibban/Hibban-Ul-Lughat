def synthesize_fast(u):
    # 1. Direct hand-crafted lexicon
    if u in DIRECT_LEXICON:
        return DIRECT_LEXICON[u]
    # 2. Existing dictionary
    if u in existing_dict:
        return existing_dict[u]

    # 3. Prefixes (O(1) checks)
    for pfx, fn in PFX_RULES.items():
        if u.startswith(pfx + " "):
            rem = u[len(pfx)+1:].strip()
            if rem in existing_dict:
                return fn(existing_dict[rem])
        elif u.startswith(pfx) and len(u) > len(pfx) + 1:
            rem = u[len(pfx):].strip()
            if rem in existing_dict:
                return fn(existing_dict[rem])

    # 4. Suffixes (O(1) checks)
    for sfx, fn in SFX_RULES.items():
        if u.endswith(" " + sfx):
            stem = u[:-len(sfx)-1].strip()
            if stem in existing_dict:
                return fn(existing_dict[stem])
        elif u.endswith(sfx) and len(u) > len(sfx) + 1:
            stem = u[:-len(sfx)].strip()
